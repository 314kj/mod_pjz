-- แผง  ทุกกล่องในหน้า Account วาดผ่านตัวนี้ตัวเดียว
--
-- 0.6.9 — เจ้าของเซิร์ฟบอกว่าหน้าจอ "เป็นเหลี่ยม ๆ ไปหมด" ซึ่งถูก
-- ของเดิมทุกกล่องคือ fill + border สีเดียวกันหมด ต่างกันแค่ตำแหน่ง
-- ตาจึงไม่มีอะไรให้ยึดว่าอันไหนสำคัญกว่าอันไหน มันเลยอ่านเป็นตารางสี่เหลี่ยม
--
-- PZ ให้เครื่องมือมาน้อยมาก: ไม่มีมุมโค้ง ไม่มีเงา ไม่มีไล่เฉด
-- **สิ่งที่ทำได้จริงคือขอบบนสว่างขึ้นหนึ่งพิกเซล กับขอบล่างมืดลงหนึ่งพิกเซล**
-- ตาคนอ่านสองเส้นนี้เป็น "ความหนา" ทันที ทั้งที่มันคือสี่เหลี่ยมแบน ๆ สองอัน
-- เป็นเทคนิคเก่าแก่จากยุค UI 16 สี และมันยังได้ผลเพราะมันเล่นกับตา ไม่ใช่กับ GPU
--
-- accent = แถบสีบางบนสุดของแผง  ใช้บอก "เรื่องอะไร" โดยไม่ต้องอ่านหัวเรื่อง
-- cap    = ป้ายหัวเรื่องบนแถบพื้นเข้ม  ทำให้หัวเรื่องเป็นหัวเรื่องจริง ๆ
--          ไม่ใช่ตัวหนังสือจาง ๆ ที่ลอยอยู่เฉย ๆ
--
-- คืนค่า y ของ "เนื้อหาบรรทัดแรก"  ผู้เรียกไม่ต้องรู้ว่าแถบหัวสูงเท่าไร
-- ==============================================================================
function U.panel(p, x, y, w, h, o)
    o = o or {}
    local bg = o.bg or U.C.bgCard

    U.fill(p, x, y, w, h, bg)

    -- ขอบสองเส้นที่ทำให้แผงดูมีความหนา  ต้องวาดก่อนกรอบ ไม่งั้นกรอบโดนทับ
    U.hr(p, x + 1, y, w - 2, U.C.line3, 0.55)              -- ขอบบนสว่าง
    U.hr(p, x + 1, y + h - 1, w - 2, U.C.bgDark, 0.75)     -- ขอบล่างมืด

    if o.accent then
        U.fill(p, x, y, w, 2, o.accent)
    end

    U.border(p, x, y, w, h, o.line or U.C.line2)

    local cy = y + (o.accent and 2 or 0)
    if o.cap then
        local ch = U.h(U.F.xs) + 10
        U.fill(p, x + 1, cy + 1, w - 2, ch, U.C.bgDark, 0.5)
        U.text(p, o.cap, x + 12, cy + 5, o.capCol or U.C.dim, U.F.xs)
        if o.capRight then
            U.textR(p, o.capRight, x + w - 12, cy + 5, o.capRightCol or U.C.mute, U.F.xs)
        end
        U.hr(p, x + 1, cy + ch + 1, w - 2, U.C.line, 0.8)
        cy = cy + ch + 2
    end
    return cy + (o.pad or 8)
end

-- ความสูงของแถบหัวเรื่องในแผง  ผู้เรียกใช้คำนวณความสูงรวมก่อนวาด
function U.capH(hasAccent)
    return (hasAccent and 2 or 0) + U.h(U.F.xs) + 10 + 2
end

function U.text(p, s, x, y, c, f, a)
    c = c or U.C.lite
    p:drawText(tostring(s), x, y, c.r, c.g, c.b, a or 1, f or U.F.s)
end

function U.textR(p, s, x, y, c, f, a)
    c = c or U.C.lite
    p:drawTextRight(tostring(s), x, y, c.r, c.g, c.b, a or 1, f or U.F.s)
end

function U.textC(p, s, x, y, c, f, a)
    c = c or U.C.lite
    p:drawTextCentre(tostring(s), x, y, c.r, c.g, c.b, a or 1, f or U.F.s)
end

function U.w(s, f)
    return getTextManager():MeasureStringX(f or U.F.s, tostring(s))
end

function U.h(f)
    return getTextManager():getFontHeight(f or U.F.s)
end

