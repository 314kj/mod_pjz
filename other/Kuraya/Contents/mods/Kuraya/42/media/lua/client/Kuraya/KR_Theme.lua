-- ก่อนหน้านี้ม็อดนี้ไม่มีตัวตัดบรรทัดเลย  ทุกข้อความจึงต้อง "สั้นพอ" ด้วยความหวัง
-- ม็อกอัปของ 0.6.11 จับได้ว่าประโยคในแผงบิลวิ่งเลยขอบหน้าต่างออกไปเลย
-- และประโยคเดิม ("The bill add-on is not installed here") ก็เลยมาตั้งแต่ 0.6.8
-- ไม่มีใครเห็นเพราะทุกคนลงม็อดภาษีไว้ ช่องนั้นจึงไม่เคยถูกวาด
--
-- **ไทยไม่มีช่องว่างระหว่างคำ** ตัดตามคำอย่างภาษาอังกฤษจึงใช้ไม่ได้กับครึ่งหนึ่งของม็อด
-- กฎที่ใช้: ถ้าบรรทัดนั้นมีช่องว่างอยู่ ให้ถอยไปตัดที่ช่องว่างตัวท้ายสุด (อ่านง่ายกว่า)
-- ถ้าไม่มีเลย ตัดตรงตัวอักษรที่ล้น  ตัดที่ "ตัวอักษร" ไม่ใช่ที่ "ไบต์"
-- ตัดที่ไบต์คือได้ครึ่งตัวอักษรไทย ซึ่งวาดออกมาเป็นขยะ (#s นับไบต์ ไม่ใช่ตัวอักษร)
-- ------------------------------------------------------------------------------
local function u8len(b)
    if b < 0x80 then return 1 end
    if b < 0xE0 then return 2 end
    if b < 0xF0 then return 3 end
    return 4
end

local function lastSpace(s)
    local at = nil
    for k = 1, #s do
        if s:sub(k, k) == " " then at = k end
    end
    return at
end

function U.wrap(s, f, maxW, maxLines)
    s = tostring(s or "")
    maxLines = maxLines or 3
    if s == "" then return { "" } end

    local lines, cur, sp = {}, "", nil
    local i, n = 1, #s

    while i <= n do
        local len = u8len(s:byte(i))
        local ch  = s:sub(i, i + len - 1)
        i = i + len

        if U.w(cur .. ch, f) > maxW and cur ~= "" then
            if sp then
                lines[#lines + 1] = cur:sub(1, sp - 1)
                cur = cur:sub(sp + 1) .. ch
            else
                lines[#lines + 1] = cur
                cur = ch
            end
            sp = lastSpace(cur)

            -- เต็มโควตาบรรทัด: จบด้วย ... ดีกว่าปล่อยให้ล้นเงียบ ๆ
            -- ข้อความที่ถูกตัดแล้วบอกว่าถูกตัด ยังซื่อสัตย์อยู่  ข้อความที่ล้นไม่ซื่อสัตย์
            if #lines >= maxLines then
                local tail = lines[maxLines]
                while tail ~= "" and U.w(tail .. "...", f) > maxW do
                    local j, cut = 1, 1
                    while j <= #tail do
                        cut = j
                        j = j + u8len(tail:byte(j))
                    end
                    tail = tail:sub(1, cut - 1)
                end
                lines[maxLines] = tail .. "..."
                return lines
            end
        else
            cur = cur .. ch
            if ch == " " then sp = #cur end
        end
    end

    if cur ~= "" then lines[#lines + 1] = cur end
    return lines
end

