function U.fill(p, x, y, w, h, c, a)
    c = c or U.C.bg
    p:drawRect(x, y, w, h, a or U.OPACITY, c.r, c.g, c.b)
end

-- พื้นทึบสนิท  ใช้กับ "กล่องที่ลอยอยู่เหนือของที่วาดไปแล้ว" เท่านั้น
--
-- ดร็อปดาวน์ / เมนู / แผงเลือกรูป / แผงโมดัล ต้องบังของข้างหลังให้มิด
-- ถ้าปล่อยให้จางตามค่าตั้งต้น ตัวหนังสือของลิสต์ข้างหลังจะทะลุขึ้นมาซ้อนกับ
-- ตัวหนังสือของเมนู = อ่านไม่ออกทั้งคู่ ซึ่งแย่กว่าไม่โปร่งใสเลย
function U.solid(p, x, y, w, h, c)
    U.fill(p, x, y, w, h, c, 1)
end

function U.border(p, x, y, w, h, c, a)
    c = c or U.C.line2
    p:drawRectBorder(x, y, w, h, a or 1, c.r, c.g, c.b)
end

-- เส้นผมบางแนวนอน  ใช้แทนการตีกรอบรอบทุกอย่าง
function U.hr(p, x, y, w, c, a)
    U.fill(p, x, y, w, 1, c or U.C.line, a or 1)
end

function U.vr(p, x, y, h, c, a)
    U.fill(p, x, y, 1, h, c or U.C.line, a or 1)
end

