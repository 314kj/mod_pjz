function U.scrollbar(p, x, y, h, total, view, offset)
    if total <= view then return end
    U.fill(p, x, y, 3, h, U.C.bgDark)
    local kh = math.max(20, math.floor(h * view / total))
    local ky = y + math.floor((h - kh) * (offset / math.max(1, total - view)))
    U.fill(p, x, ky, 3, kh, U.C.accent2)
end


