function U.emptyState(p, x, y, w, h, title, hint)
    local room = math.max(60, w - 24)
    local tl = U.wrap(title, U.F.m, room, 2)
    local hl = hint and U.wrap(hint, U.F.s, room, 3) or nil

    local th, hh = U.h(U.F.m), U.h(U.F.s)
    local total = #tl * th + (hl and (6 + #hl * hh) or 0)
    local cy = y + math.floor((h - total) / 2)
    if cy < y then cy = y end

    for i = 1, #tl do
        U.textC(p, tl[i], x + w / 2, cy, U.C.mute, U.F.m)
        cy = cy + th
    end
    if hl then
        cy = cy + 6
        for i = 1, #hl do
            U.textC(p, hl[i], x + w / 2, cy, U.C.dim, U.F.s)
            cy = cy + hh
        end
    end
end

