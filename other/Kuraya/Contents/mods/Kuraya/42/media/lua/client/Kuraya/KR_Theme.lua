--
-- ใช้อาร์ตจริงเก้ารูปที่เจ้าของเซิร์ฟส่งมา (media/textures/Kuraya/hfp/hfp1..9.png)
-- แอดมินเลือกได้ว่ารูปไหนอยู่ช่องไหน  เก็บเป็น id ไม่ใช่ path
--
-- ยังมีทางสำรองเป็นสี่เหลี่ยมอยู่ข้างล่าง  ไม่ใช่ของเหลือจากเวอร์ชันก่อน
-- แต่เป็นทางที่ต้องเดินได้จริงสองกรณี: เซฟที่เก็บ id ชุดเก่าไว้ และไฟล์รูปหาย
-- ------------------------------------------------------------------------------
-- โหลดครั้งเดียวแล้วเก็บไว้  getTexture ทุกเฟรมคือการค้นหาไฟล์ทุกเฟรม
-- เก็บ false ไว้ด้วยเมื่อหาไม่เจอ  ไม่งั้นไฟล์ที่หายจะถูกค้นซ้ำทุกเฟรมตลอดเซสชัน
local hfpTex = {}
local function hfpTexOf(id)
    if hfpTex[id] ~= nil then return hfpTex[id] or nil end
    local t = getTexture("media/textures/Kuraya/hfp/" .. tostring(id) .. ".png")
    -- getTexture ของ PZ คืน object กลับมาได้แม้ไฟล์จะเสีย  เช็กว่ามันตอบความกว้างได้จริง
    -- (ไฟล์ 24-bit RGB คืน object ที่วาดออกมาเป็นสี่เหลี่ยมใส ซึ่งแย่กว่าไฟล์หาย
    --  เพราะทางสำรองไม่ถูกเดินเลย  บทเรียนจากคู่มือไทย 29 หน้าที่ไม่ขึ้นสักหน้า)
    if t and type(t.getWidth) ~= "function" then t = nil end
    hfpTex[id] = t or false
    return t
end

function U.hfpIcon(p, id, x, y, size, col)
    -- รูปจริงก่อน  แอดมินเลือกจากเก้ารูปที่แถมมากับม็อด
    local t = hfpTexOf(id)
    if t then
        -- col ทำหน้าที่เป็น tint  ใช้หรี่รูปของแพ็กที่ปิดอยู่ให้ดูจางลงทั้งใบ
        local r, g, b = 1, 1, 1
        if col then r, g, b = col.r or 1, col.g or 1, col.b or 1 end
        p:drawTextureScaled(t, x, y, size, size, 1, r, g, b)
        return
    end

    -- ---- ทางสำรอง : วาดด้วยสี่เหลี่ยม -----------------------------------------
    --
    -- ยังเก็บไว้เพราะสองเหตุผล
    --   1. เซฟที่ตั้งค่าไว้ก่อนจะมีอาร์ตจริง เก็บ id เก่า (coin/stack/box/gem/star/clock)
    --      ถ้าลบทิ้ง แพ็กพวกนั้นจะกลายเป็นช่องว่างเปล่าโดยไม่มีอะไรอธิบาย
    --   2. ไฟล์รูปหายด้วยเหตุใดก็ตาม ต้องยังมีอะไรให้เห็น ไม่ใช่รูสี่เหลี่ยมใส ๆ
    col = col or U.C.mute
    local function r(fx, fy, fw, fh)
        U.fill(p, x + math.floor(fx * size), y + math.floor(fy * size),
                  math.max(1, math.floor(fw * size)), math.max(1, math.floor(fh * size)), col)
    end

    if id == "stack" then
        r(0.18, 0.22, 0.64, 0.14); r(0.14, 0.42, 0.72, 0.14); r(0.10, 0.62, 0.80, 0.16)
    elseif id == "box" then
        r(0.12, 0.26, 0.76, 0.14); r(0.16, 0.40, 0.68, 0.38); r(0.44, 0.26, 0.12, 0.52)
    elseif id == "gem" then
        r(0.30, 0.24, 0.40, 0.10); r(0.20, 0.34, 0.60, 0.12)
        r(0.28, 0.46, 0.44, 0.14); r(0.40, 0.60, 0.20, 0.16)
    elseif id == "star" then
        r(0.44, 0.14, 0.12, 0.20); r(0.14, 0.34, 0.72, 0.12); r(0.26, 0.46, 0.48, 0.12)
        r(0.20, 0.58, 0.16, 0.20); r(0.64, 0.58, 0.16, 0.20)
    elseif id == "clock" then
        r(0.42, 0.10, 0.16, 0.08); r(0.24, 0.22, 0.52, 0.08)
        r(0.16, 0.30, 0.68, 0.44); r(0.24, 0.74, 0.52, 0.08)
    else
        r(0.30, 0.24, 0.40, 0.08); r(0.22, 0.32, 0.56, 0.36); r(0.30, 0.68, 0.40, 0.08)
    end
end


