function U.titleBar(p, w, name, sub, mx, my, mood)
    U.fill(p, 0, 0, w, U.TITL, U.C.bgDark)
    local ls = U.TITL - 6
    local lw = U.logo(p, 5, 3, ls, mood)
    local nx = (lw > 0) and (5 + lw + 6) or 10
    local ty = math.floor((U.TITL - U.h(U.F.s)) / 2)
    U.text(p, name, nx, ty, U.C.text, U.F.s)
    if sub then
        U.text(p, sub, nx + 2 + U.w(name, U.F.s), ty, U.C.dim, U.F.s)
    end

    local bx  = w - U.TITL
    local hot = mx and mx >= bx and mx < bx + U.TITL and my and my >= 0 and my < U.TITL
    U.textC(p, "X", bx + U.TITL / 2, ty, hot and U.C.text or U.C.mute, U.F.s)

    local hx  = bx - U.TITL
    local hhot = mx and mx >= hx and mx < hx + U.TITL and my and my >= 0 and my < U.TITL
    U.textC(p, "?", hx + U.TITL / 2, ty, hhot and U.C.text or U.C.accent, U.F.s)

    return { x = bx, y = 0, w = U.TITL, h = U.TITL },
           { x = hx, y = 0, w = U.TITL, h = U.TITL }
end

