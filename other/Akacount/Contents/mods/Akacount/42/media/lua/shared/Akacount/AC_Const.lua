-- ชนิดไอเทมของลายนั้น  ลายที่ม็อดอื่นลงทะเบียนเข้ามาไม่มีไอเทมของตัวเอง
-- จึงตกกลับมาใช้ใบมาตรฐาน  ดีกว่าออกบัตรไม่ได้เลย
function AC.cardItemOf(id)
    local s = AC.skinById(id)
    return (s and s.item) or AC.ITEM_CARD
end

-- ชนิดไอเทมทั้งหมดที่นับว่าเป็น "บัตร Akacount"
-- ทุกที่ที่ต้องไล่หาบัตรในกระเป๋าต้องวนตามลิสต์นี้ ไม่ใช่หาแค่ AC.ITEM_CARD
local _cardTypes, _cardSet
function AC.cardTypes()
    if _cardTypes then return _cardTypes end
    _cardTypes, _cardSet = {}, {}
    local function add(ft)
        if ft and not _cardSet[ft] then
            _cardSet[ft] = true
            _cardTypes[#_cardTypes + 1] = ft
        end
    end
    add(AC.ITEM_CARD)
    for _, s in ipairs(AC.CARD_SKINS_BUILTIN) do add(s.item) end
    return _cardTypes
end

function AC.isCardItem(fullType)
    if fullType == nil then return false end
    AC.cardTypes()
    return _cardSet[fullType] == true
end

